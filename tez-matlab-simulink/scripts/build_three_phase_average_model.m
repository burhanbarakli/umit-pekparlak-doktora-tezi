% Üç fazlı dört telli LCL/PR/Sin^3 ortalama değer Simulink modelini kurar.

root_dir=fileparts(fileparts(mfilename('fullpath')));
run(fullfile(root_dir,'parameters','three_phase_demo_parameters.m'));
Simulink.fileGenControl('set', ...
    'CacheFolder',fullfile(root_dir,'build','cache'), ...
    'CodeGenFolder',fullfile(root_dir,'build','codegen'),'createDir',true);
model_name='t_type_three_phase_four_wire_average';
model_file=fullfile(root_dir,'models',[model_name '.slx']);
if bdIsLoaded(model_name),close_system(model_name,0);end
if exist(model_file,'file'),delete(model_file);end
new_system(model_name); open_system(model_name);
set_param(model_name,'Solver','ode23tb','StopTime','t_stop_3ph', ...
    'MaxStep','1e-5','ReturnWorkspaceOutputs','on');
set_param(model_name,'PreLoadFcn', ...
    "demo_root=fileparts(fileparts(get_param(bdroot,'FileName'))); run(fullfile(demo_root,'parameters','three_phase_demo_parameters.m')); clear demo_root;");

phase_names={'A','B','C'};
colors={'lightBlue','yellow','green'};
for p=1:3
    y0=40+(p-1)*235;
    ph=phase_names{p};
    phase_expr=sprintf('phase_shift_3ph(%d)',p);
    add_block('simulink/Sources/Sine Wave',[model_name '/i_ref_' ph], ...
        'Amplitude','I_ref_pk_3ph','Frequency','w_grid_sw','Phase',phase_expr, ...
        'Position',[25 y0 85 y0+30]);
    add_block('simulink/Sources/Sine Wave',[model_name '/v_grid_' ph], ...
        'Amplitude','V_grid_pk_3ph','Frequency','w_grid_sw','Phase',phase_expr, ...
        'Position',[25 y0+55 85 y0+85]);
    add_block('simulink/Sources/Sine Wave',[model_name '/sin_theta_' ph], ...
        'Amplitude','1','Frequency','w_grid_sw','Phase',phase_expr, ...
        'Position',[25 y0+105 85 y0+135]);
    add_block('simulink/Math Operations/Sum',[model_name '/error_' ph], ...
        'Inputs','+-','Position',[130 y0 160 y0+40]);
    add_block('simulink/Math Operations/Gain',[model_name '/P_' ph], ...
        'Gain','Kp_3ph','Position',[195 y0-5 245 y0+25]);
    add_block('simulink/Continuous/Transfer Fcn',[model_name '/R_' ph], ...
        'Numerator','[2*Kr_3ph*wc_3ph 0]', ...
        'Denominator','[1 2*wc_3ph w_grid_sw^2]', ...
        'Position',[195 y0+40 275 y0+75]);
    add_block('simulink/User-Defined Functions/Fcn',[model_name '/sin3_' ph], ...
        'Expr','u^3','Position',[120 y0+105 175 y0+140]);
    add_block('simulink/Math Operations/Gain',[model_name '/dist_gain_' ph], ...
        'Gain','Kdist_3ph','Position',[205 y0+95 265 y0+125]);
    add_block('simulink/Math Operations/Gain',[model_name '/comp_gain_' ph], ...
        'Gain','Ksin3_3ph','Position',[205 y0+140 265 y0+170]);
    add_block('simulink/Sources/Constant',[model_name '/supp_enable_' ph], ...
        'Value','suppression_effect_enable_3ph','Position',[285 y0+90 330 y0+120]);
    add_block('simulink/Sources/Constant',[model_name '/sin3_enable_' ph], ...
        'Value','sin3_enable_3ph','Position',[285 y0+145 330 y0+175]);
    add_block('simulink/Math Operations/Product',[model_name '/dist_switch_' ph], ...
        'Position',[360 y0+92 395 y0+128]);
    add_block('simulink/Math Operations/Product',[model_name '/comp_switch_' ph], ...
        'Position',[360 y0+140 395 y0+176]);
    add_block('simulink/Math Operations/Sum',[model_name '/v_command_' ph], ...
        'Inputs','+++++','Position',[430 y0+5 460 y0+120]);
    add_block('simulink/Discontinuities/Saturation',[model_name '/v_limit_' ph], ...
        'UpperLimit','Vdc_sw/2','LowerLimit','-Vdc_sw/2', ...
        'Position',[500 y0+35 565 y0+75]);
    add_block('simulink/Signal Routing/Mux',[model_name '/plant_mux_' ph], ...
        'Inputs','2','Position',[600 y0+35 605 y0+95]);
    add_block('simulink/Continuous/State-Space',[model_name '/LCL_' ph], ...
        'A','A_lcl_3ph','B','B_lcl_3ph','C','C_lcl_3ph','D','D_lcl_3ph', ...
        'X0','[0 0 0]','Position',[645 y0+35 735 y0+95]);
    add_block('simulink/Sinks/To Workspace',[model_name '/save_i_' ph], ...
        'VariableName',['i_' lower(ph) '_3ph_log'],'SaveFormat','Timeseries', ...
        'Position',[775 y0+35 850 y0+65]);
    add_block('simulink/Sinks/To Workspace',[model_name '/save_ref_' ph], ...
        'VariableName',['ref_' lower(ph) '_3ph_log'],'SaveFormat','Timeseries', ...
        'Position',[25 y0-35 100 y0-5]);

    add_line(model_name,['i_ref_' ph '/1'],['error_' ph '/1'],'autorouting','on');
    add_line(model_name,['i_ref_' ph '/1'],['save_ref_' ph '/1'],'autorouting','on');
    add_line(model_name,['LCL_' ph '/1'],['error_' ph '/2'],'autorouting','on');
    add_line(model_name,['error_' ph '/1'],['P_' ph '/1'],'autorouting','on');
    add_line(model_name,['error_' ph '/1'],['R_' ph '/1'],'autorouting','on');
    add_line(model_name,['sin_theta_' ph '/1'],['sin3_' ph '/1'],'autorouting','on');
    add_line(model_name,['sin3_' ph '/1'],['dist_gain_' ph '/1'],'autorouting','on');
    add_line(model_name,['sin3_' ph '/1'],['comp_gain_' ph '/1'],'autorouting','on');
    add_line(model_name,['dist_gain_' ph '/1'],['dist_switch_' ph '/1'],'autorouting','on');
    add_line(model_name,['supp_enable_' ph '/1'],['dist_switch_' ph '/2'],'autorouting','on');
    add_line(model_name,['comp_gain_' ph '/1'],['comp_switch_' ph '/1'],'autorouting','on');
    add_line(model_name,['sin3_enable_' ph '/1'],['comp_switch_' ph '/2'],'autorouting','on');
    add_line(model_name,['P_' ph '/1'],['v_command_' ph '/1'],'autorouting','on');
    add_line(model_name,['R_' ph '/1'],['v_command_' ph '/2'],'autorouting','on');
    add_line(model_name,['v_grid_' ph '/1'],['v_command_' ph '/3'],'autorouting','on');
    add_line(model_name,['dist_switch_' ph '/1'],['v_command_' ph '/4'],'autorouting','on');
    add_line(model_name,['comp_switch_' ph '/1'],['v_command_' ph '/5'],'autorouting','on');
    add_line(model_name,['v_command_' ph '/1'],['v_limit_' ph '/1'],'autorouting','on');
    add_line(model_name,['v_limit_' ph '/1'],['plant_mux_' ph '/1'],'autorouting','on');
    add_line(model_name,['v_grid_' ph '/1'],['plant_mux_' ph '/2'],'autorouting','on');
    add_line(model_name,['plant_mux_' ph '/1'],['LCL_' ph '/1'],'autorouting','on');
    add_line(model_name,['LCL_' ph '/1'],['save_i_' ph '/1'],'autorouting','on');
    set_param([model_name '/LCL_' ph],'BackgroundColor',colors{p});
end

% Dört telli nötr akımı: i_n=-(i_a+i_b+i_c)
add_block('simulink/Math Operations/Sum',[model_name '/neutral_current'], ...
    'Inputs','+++','Position',[900 255 930 360]);
add_block('simulink/Math Operations/Gain',[model_name '/neutral_sign'], ...
    'Gain','-1','Position',[960 285 1010 325]);
add_block('simulink/Sinks/To Workspace',[model_name '/save_neutral'], ...
    'VariableName','i_neutral_3ph_log','SaveFormat','Timeseries', ...
    'Position',[1045 290 1130 320]);
for p=1:3
    ph=phase_names{p};
    add_line(model_name,['LCL_' ph '/1'],sprintf('neutral_current/%d',p),'autorouting','on');
end
add_line(model_name,'neutral_current/1','neutral_sign/1','autorouting','on');
add_line(model_name,'neutral_sign/1','save_neutral/1','autorouting','on');

note=Simulink.Annotation(model_name, ...
    'ÜÇ FAZ DÖRT TELLİ ORTALAMA MODEL: Sin^3 üçüncü harmonikleri nötrde aynı fazda toplanır');
note.Position=[680 5];
save_system(model_name,model_file); close_system(model_name,0);
fprintf('Üç faz ortalama model oluşturuldu: %s\n',model_file);
